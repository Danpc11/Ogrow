#!/usr/bin/env python
"""Check that every model number in MANUSCRIPT.md still matches the results.

Six times in this project a number written into prose drifted away from the
table that produced it, because the prose was written once and the tables are
regenerated by `make paper`. The manuscript is the worst place for that to
happen, since it is the file that leaves the repository.

So the manuscript quotes nothing this script cannot find. Each check below
reads a value out of the result files, formats it exactly as the manuscript
writes it, and requires that string to appear. If a rerun moves the value, the
formatted string stops matching and this fails with the old text and the new
value side by side. It does not parse the manuscript or guess at context: a
number that moved is a failure, and the fix is to edit the sentence.

Run it after `make paper`. It needs only the standard library plus numpy.

Usage:  python scripts/29_check_manuscript.py
"""
import json
import sys

import numpy as np

from organgrow.config import ROOT

RES = ROOT / "results"
DOC = ROOT / "MANUSCRIPT.md"
checks = []       # (label, the string the manuscript must contain)


def need(label, text):
    checks.append((label, str(text)))


def load(name):
    p = RES / name
    return json.load(open(p)) if p.exists() else None


# ------------------------------------------------- regimes at closure
rp = RES / "paper" / "regime_reps.json"
if rp.exists():
    R = json.load(open(rp))

    def ms(reg, group, key, nd=2):
        d = R[reg][group][key]
        return f"{d['mean']:.{nd}f} ± {d['se']:.{nd}f}"

    for reg in ("liver", "kidney", "pancreas"):
        n = R[reg]["N"]
        need(f"{reg} unit count", f"{n['mean']:.0f} ± {n['se']:.0f}")
    need("liver held by supply", ms("liver", "closure", "supply_held"))
    need("liver held by room", ms("liver", "closure", "space_held"))
    need("pancreas consumed", ms("pancreas", "fate", "consumed"))
    need("pancreas still held", ms("pancreas", "fate", "left"))
    need("kidney consumed", ms("kidney", "fate", "consumed"))
    need("kidney lost to attrition", ms("kidney", "fate", "lost"))

# ------------------------------------------------- elasticities
E = load("elasticity.json")
if E:
    for reg in ("liver", "kidney", "pancreas"):
        v = E.get(f"{reg}_ref", {})
        if "P0" in v:
            need(f"{reg} pool elasticity",
                 f"+{v['P0']['mean']:.2f} ± {v['P0']['se']:.2f}")
        if "q_set" in v:
            need(f"{reg} setpoint elasticity",
                 f"{v['q_set']['mean']:.2f} ± {v['q_set']['se']:.2f}")

# ------------------------------------------------- interventions
I = load("interventions.json")
if I:
    def pct(key):
        v = I[key]
        return f"{100 * v['units_added']:.1f} ± {100 * v['units_added_se']:.1f} %"

    need("liver, unchanged", pct("liver_none"))
    need("liver, supply relieved", pct("liver_supply"))
    need("liver, room relieved", pct("liver_room"))
    need("pancreas, supply relieved", pct("pancreas_supply"))
    need("pancreas, room relieved", pct("pancreas_room"))
    need("kidney pool on day 140", f"{I['kidney_none']['pool']:.1f} cells")

# ------------------------------------------------- injury
J = load("injury.json")
if J:
    def band(key, field, nd=2):
        d = J[key][field]
        v = d["seeds"]
        return f"{d['mean']:.{nd}f} [{min(v):.{nd}f}, {max(v):.{nd}f}]"

    need("liver as grown, units", band("liver_as grown", "units"))
    need("liver as grown, mass", band("liver_as grown", "mass"))
    need("liver as grown, perfused mass", band("liver_as grown", "perfused"))
    need("liver reactivated, mass", band("liver_reactivated", "mass"))
    need("kidney reactivated, mass", band("kidney_reactivated", "mass"))
    need("liver at fixed inflow, mass",
         band("liver_reactivated, fixed inflow", "mass"))
    need("kidney at fixed inflow, mass",
         band("kidney_reactivated, fixed inflow", "mass"))
    for frac in ("0.3", "0.5"):
        k = f"kidney_compensation_{frac}"
        if k in J:
            need(f"kidney after a {frac} loss, mass per unit",
                 band(k, "mass_per_unit"))
            need(f"full compensation after a {frac} loss",
                 f"{J[k]['full']:.2f}")
    if "kidney_compensation_0.3" in J:
        need("kidney units kept after a 0.3 loss",
             band("kidney_compensation_0.3", "units"))

# --------------------------- spread across seeds, computed as the table does
if J:
    def cv(d):
        v = np.asarray(d["seeds"], float)
        return 100.0 * v.std(ddof=1) / v.mean() if v.mean() else float("nan")

    for reg in ("liver", "kidney"):
        free = J.get(f"{reg}_reactivated")
        held = J.get(f"{reg}_reactivated, fixed inflow")
        if not (free and held):
            continue
        for field, lab in (("mass", "mass"), ("units", "unit count")):
            need(f"{reg} {lab}, inlet pressure fixed", f"{cv(free[field]):.1f} %")
            need(f"{reg} {lab}, inflow held", f"{cv(held[field]):.1f} %")

# ------------------------------------------------- scaling
Sc = load("scaling.json")
if Sc:
    for mode, tag in (("geometry", "geometry"), ("allometric", "allometric")):
        if mode in Sc:
            need(f"{tag} exponent", f"V^{{{Sc[mode]['exponent']:.2f}}}")
    rows = Sc.get("geometry", {}).get("rows", [])
    if rows:
        S = sorted({r["S"] for r in rows})
        for s, lab in ((S[0], "smallest"), (S[-1], "largest")):
            g = [r for r in rows if r["S"] == s]
            m = (lambda k, g=g: float(np.mean([x[k] for x in g])))
            need(f"{lab} domain, held by supply", f"{m('supply_held'):.2f}")
            need(f"{lab} domain, held by room", f"{m('space_held'):.2f}")
            need(f"{lab} domain, close packing", f"{100 * m('fill'):.1f} %")
        cvs = []
        for s in S:
            N = np.array([r["N"] for r in rows if r["S"] == s], float)
            cvs.append(N.std(ddof=1) / max(N.mean(), 1e-9))
        need("CV at the two smallest domains", f"{cvs[0]:.2f}")
        need("CV, third domain", f"{cvs[-2]:.2f}")
        need("CV, largest domain", f"{cvs[-1]:.2f}")
        N = np.array([r["N"] for r in rows if r["S"] == S[-1]], float)
        need("span at the largest domain", f"{N.min():.0f} to {N.max():.0f}")

# ------------------------------------------------- transcriptome
T = load("transcriptome.json")
if T:
    sp = T.get("spearman", {})
    if "npc_share" in sp:
        need("kidney progenitor share against stage",
             f"\\rho = {sp['npc_share'][0]:+.2f}$, $P = {sp['npc_share'][1]:.2f}")
    if "induced_per_npc" in sp:
        need("induced per progenitor against stage",
             f"\\rho = {sp['induced_per_npc'][0]:+.2f}$, $P = {sp['induced_per_npc'][1]:.2f}")
    k2 = T.get("kidney_second_study")
    if k2:
        sh = float(k2["npc"][0]) / max(float(k2["lineage"][0]), 1.0)
        need("independent week-14 kidney", f"{sh:.3f}")
    for organ in ("kidney", "pancreas", "liver"):
        wdw = T.get("windows", {}).get(organ)
        if wdw:
            need(f"{organ}, progenitor share at the last stage",
                 f"{wdw['share']:.4f}")
            need(f"{organ}, fraction of the window elapsed",
                 f"{wdw['window_fraction']:.0%}".replace("%", " %"))


def main():
    if not DOC.exists():
        raise SystemExit(f"no manuscript at {DOC}")
    # the manuscript sets a minus as U+2212; compare against a plain hyphen
    text = DOC.read_text(encoding="utf-8").replace("\u2212", "-")
    if not checks:
        print("no results to check against; run `make paper` first")
        return 0
    bad = [(label, want) for label, want in checks if want not in text]
    for label, want in checks:
        print(f"  {'ok  ' if want in text else 'FAIL'} {label}: {want}")
    print()
    if bad:
        print(f"{len(bad)} of {len(checks)} numbers in MANUSCRIPT.md no longer "
              f"match the results. The results are right and the prose is "
              f"stale: edit the sentence to the value printed above.")
        return 1
    print(f"all {len(checks)} model numbers in MANUSCRIPT.md match the results")
    return 0


if __name__ == "__main__":
    sys.exit(main())
