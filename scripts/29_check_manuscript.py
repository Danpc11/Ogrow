#!/usr/bin/env python
"""Check that every model number in MANUSCRIPT.md still matches the results.

Six times in this project a number written into prose drifted away from the
table that produced it, because the prose was written once and the tables are
regenerated by `make paper`. The manuscript is the worst place for that to
happen, since it is the file that leaves the repository.

So the manuscript quotes nothing this script cannot find. Each check below
reads a value out of the result files, formats it exactly as the manuscript
writes it, and requires that string to appear. If a rerun moves the value, the
formatted string stops matching and this fails with the old text and the new
value side by side. It does not parse the manuscript or guess at context: a
number that moved is a failure, and the fix is to edit the sentence.

It is a consistency barrier, not a scientific audit: it holds the prose to the
tables it quotes, and says nothing about whether a causal claim in the text is
warranted or whether a number nobody listed here is right.

Run it after `make paper`. It needs only the standard library plus numpy.

Usage:  python scripts/29_check_manuscript.py
"""
import json
import sys

import numpy as np

from organgrow.config import ROOT

RES = ROOT / "results"
DOC = ROOT / "MANUSCRIPT.md"
checks = []       # (label, the string the manuscript must contain)


def need(label, text):
    checks.append((label, str(text)))


def load(name):
    p = RES / name
    return json.load(open(p)) if p.exists() else None


# ------------------------------------------------- regimes at closure
rp = RES / "paper" / "regime_reps.json"
if rp.exists():
    R = json.load(open(rp))

    def ms(reg, group, key, nd=2):
        d = R[reg][group][key]
        return f"{d['mean']:.{nd}f} ± {d['se']:.{nd}f}"

    for reg in ("liver", "kidney", "pancreas"):
        n = R[reg]["N"]
        need(f"{reg} unit count", f"{n['mean']:.0f} ± {n['se']:.0f}")
    need("liver held by supply", ms("liver", "closure", "supply_held"))
    need("liver held by room", ms("liver", "closure", "space_held"))
    need("pancreas consumed", ms("pancreas", "fate", "consumed"))
    need("pancreas still held", ms("pancreas", "fate", "left"))
    need("kidney consumed", ms("kidney", "fate", "consumed"))
    need("kidney lost to attrition", ms("kidney", "fate", "lost"))

# ------------------------------------------------- elasticities
E = load("elasticity.json")
if E:
    for reg in ("liver", "kidney", "pancreas"):
        v = E.get(f"{reg}_ref", {})
        if "P0" in v:
            need(f"{reg} pool elasticity",
                 f"+{v['P0']['mean']:.2f} ± {v['P0']['se']:.2f}")
        if "q_set" in v:
            need(f"{reg} setpoint elasticity",
                 f"{v['q_set']['mean']:.2f} ± {v['q_set']['se']:.2f}")

# ------------------------------------------------- interventions
I = load("interventions.json")
if I:
    def pct(key):
        v = I[key]
        return f"{100 * v['units_added']:.1f} ± {100 * v['units_added_se']:.1f} %"

    need("liver, unchanged", pct("liver_none"))
    need("liver, supply relieved", pct("liver_supply"))
    need("liver, room relieved", pct("liver_room"))
    need("pancreas, supply relieved", pct("pancreas_supply"))
    need("pancreas, room relieved", pct("pancreas_room"))
    need("kidney pool on day 140", f"{I['kidney_none']['pool']:.1f} cells")

# ------------------------------------------------- injury
J = load("injury.json")
if J:
    def band(key, field, nd=2):
        d = J[key][field]
        v = d["seeds"]
        return f"{d['mean']:.{nd}f} [{min(v):.{nd}f}, {max(v):.{nd}f}]"

    need("liver as grown, units", band("liver_as grown", "units"))
    need("liver as grown, mass", band("liver_as grown", "mass"))
    need("liver as grown, perfused mass", band("liver_as grown", "perfused"))
    need("liver reactivated, mass", band("liver_reactivated", "mass"))
    need("kidney reactivated, mass", band("kidney_reactivated", "mass"))
    need("liver at fixed inflow, mass",
         band("liver_reactivated, fixed inflow", "mass"))
    need("kidney at fixed inflow, mass",
         band("kidney_reactivated, fixed inflow", "mass"))
    for frac in ("0.3", "0.5"):
        k = f"kidney_compensation_{frac}"
        if k in J:
            need(f"kidney after a {frac} loss, mass per unit",
                 band(k, "mass_per_unit"))
            need(f"full compensation after a {frac} loss",
                 f"{J[k]['full']:.2f}")
    if "kidney_compensation_0.3" in J:
        need("kidney units kept after a 0.3 loss",
             band("kidney_compensation_0.3", "units"))

# --------------------------- spread across seeds, computed as the table does
if J:
    def cv(d):
        v = np.asarray(d["seeds"], float)
        return 100.0 * v.std(ddof=1) / v.mean() if v.mean() else float("nan")

    for reg in ("liver", "kidney"):
        free = J.get(f"{reg}_reactivated")
        held = J.get(f"{reg}_reactivated, fixed inflow")
        if not (free and held):
            continue
        # only the mass; the manuscript no longer quotes the unit-count spread
        need(f"{reg} mass, inlet pressure fixed", f"{cv(free['mass']):.1f} %")
        need(f"{reg} mass, inflow held", f"{cv(held['mass']):.1f} %")

# ------------------------------------------------- scaling
Sc = load("scaling.json")
if Sc:
    for mode, tag in (("geometry", "geometry"), ("allometric", "allometric")):
        if mode in Sc:
            need(f"{tag} exponent", f"V^{{{Sc[mode]['exponent']:.2f}}}")
    rows = Sc.get("geometry", {}).get("rows", [])
    if rows:
        S = sorted({r["S"] for r in rows})
        for s, lab in ((S[0], "smallest"), (S[-1], "largest")):
            g = [r for r in rows if r["S"] == s]
            m = (lambda k, g=g: float(np.mean([x[k] for x in g])))
            need(f"{lab} domain, held by supply", f"{m('supply_held'):.2f}")
            need(f"{lab} domain, held by room", f"{m('space_held'):.2f}")
            need(f"{lab} domain, close packing", f"{100 * m('fill'):.1f} %")
        cvs = []
        for s in S:
            N = np.array([r["N"] for r in rows if r["S"] == s], float)
            cvs.append(N.std(ddof=1) / max(N.mean(), 1e-9))
        need("CV at the two smallest domains", f"{cvs[0]:.2f}")
        need("CV, third domain", f"{cvs[-2]:.2f}")
        need("CV, largest domain", f"{cvs[-1]:.2f}")
        N = np.array([r["N"] for r in rows if r["S"] == S[-1]], float)
        need("span at the largest domain", f"{N.min():.0f} to {N.max():.0f}")

# ------------------------------------------------- transcriptome
T = load("transcriptome.json")
if T:
    sp = T.get("spearman", {})
    if "npc_share" in sp:
        need("kidney progenitor share against stage",
             f"\\rho = {sp['npc_share'][0]:+.2f}$, $P = {sp['npc_share'][1]:.2f}")
    if "induced_per_npc" in sp:
        need("induced per progenitor against stage",
             f"\\rho = {sp['induced_per_npc'][0]:+.2f}$, $P = {sp['induced_per_npc'][1]:.2f}")
    k2 = T.get("kidney_second_study")
    if k2:
        sh = float(k2["npc"][0]) / max(float(k2["lineage"][0]), 1.0)
        need("independent week-14 kidney", f"{sh:.3f}")
    for organ in ("kidney", "pancreas", "liver"):
        wdw = T.get("windows", {}).get(organ)
        if wdw:
            need(f"{organ}, progenitor share at the last stage",
                 f"{wdw['share']:.4f}")
            need(f"{organ}, fraction of the window elapsed",
                 f"{wdw['window_fraction']:.0%}".replace("%", " %"))


# ------------------------------------------------- the supply budget sweep
L = load("inflow_law.json")
if L and "liver" in L:
    d = L["liver"]
    # Two decimals: the third moves between machines and between calibration
    # blocks, and the table in PAPER_NUMBERS carries the full precision.
    need("mass against delivered flow, exponent", f"exponent of {d['slope']:.2f}")
    lo, hi = d["rows"][0], d["rows"][-1]
    need("overshoot of the budget at the lowest flow",
         f"about {lo['mass_over_law']:.1f} times")
    need("shortfall against the budget at the highest flow",
         f"about {hi['mass_over_law']:.1f} of it")

# The residual and the share at the mass floor are what keep Section 3.4 from
# calling the plateau an equilibrium, so the sentence that reports them is held
# to the numbers like any other.
if L:
    for _reg, _lab in (("liver", "renewing construct"),
                       ("kidney", "spent source")):
        if _reg not in L:
            continue
        _rows = L[_reg]["rows"]
        _res = [x["residual"] for x in _rows if x.get("residual") is not None]
        _flo = [x["floor_share"] for x in _rows if x.get("floor_share") is not None]
        # The worst of each, which is the number the sentence turns on. Quoting
        # both ends of the range would put two roundings in the way of one
        # claim, and the table in PAPER_NUMBERS carries every flow.
        if _res:
            need(f"{_lab}, largest residual", f"as much as {max(_res):.2f}")
        if _flo:
            need(f"{_lab}, largest share at the mass floor",
                 f"up to {round(100 * max(_flo))} %")

# The involution sensitivity. Each string below sits on one line of the
# manuscript, because a check that spanned a line break would fail on
# rewrapping rather than on a number moving.
Iv = load("involution.json")
if Iv and "liver" in Iv and "kidney" in Iv:
    def _at(reg, rate):
        for r in Iv[reg]["rows"]:
            if abs(r["rate"] - rate) < 1e-12:
                return r
        return None

    lv0, lv5 = _at("liver", 0.0), _at("liver", 0.05)
    kd0, kd5 = _at("kidney", 0.0), _at("kidney", 0.05)
    if lv0 and lv5 and kd0 and kd5:
        need("renewing construct under involution, mass",
             f"{lv5['mass_rel']:.2f} of its pre-injury mass, against "
             f"{lv0['mass_rel']:.2f} without the mechanism")
        need("renewing construct under involution, units",
             f"with {lv5['units_rel']:.2f} of its pre-injury unit count rather "
             f"than {lv0['units_rel']:.2f}")
        need("spent source under involution, units and mass",
             f"units to {kd5['units_rel']:.2f} at an unchanged "
             f"{kd5['mass_rel']:.2f} of its mass")
        need("share at the mass floor under involution",
             f"floor falls from {lv0['floor_share']:.2f} to "
             f"{lv5['floor_share']:.2f} in the renewing construct and from "
             f"{kd0['floor_share']:.2f} to {kd5['floor_share']:.2f}")
        # Only where it lands. The residual without the mechanism is already
        # checked above, at two decimals of a value whose third decimal sits
        # on a rounding boundary, and one claim should not carry two of those.
        need("residual under involution",
             f"to {lv5['residual']:.2f} in the renewing construct and to "
             f"{kd5['residual']:.2f} in")
    u_l, u_k = Iv["liver"].get("units_rel_on"), Iv["kidney"].get("units_rel_on")
    if u_l and u_k:
        need("units kept across the rates, renewing",
             f"keeps between {u_l[0]:.2f} and {u_l[1]:.2f} of its units")
        need("units kept across the rates, spent",
             f"source between {u_k[0]:.2f} and {u_k[1]:.2f}")


# ------------------------------------------------- what separates the regimes
Rg = load("regimes.json")
if Rg:
    mt = Rg.get("_meta", {})
    if "turnover_flips" in mt:
        need("renewal changes the bound",
             f"in {mt['renewal_flips']} of the {mt['cells']} settings of the "
             f"other two")
        need("turnover changes the bound",
             f"in {mt['turnover_flips']} of the {mt['other_cells']} settings "
             f"of renewal and the pool")
        need("pool changes the bound",
             f"the pool alone in {mt['pool_flips']} of {mt['other_cells']}")
        # the abstract states the same two counts in its own words, and a
        # count that moved must fail there too rather than quietly survive
        need("renewal changes the bound, abstract",
             f"in {mt['renewal_flips']} of {mt['cells']} settings of the "
             f"other two")
        need("turnover changes the bound, abstract",
             f"the turnover in {mt['turnover_flips']} of {mt['other_cells']}")
    el = Rg.get("_elasticity_matched") or {}
    #: the gap the binary property keeps once the pool and the turnover are
    #: matched, at each of the three published corners
    corner = {"balanced": "liver-like", "decaying": "kidney-like",
              "static": "pancreas-like"}
    for v in el.values():
        nm = corner.get(v.get("turnover"))
        if nm:
            need(f"matched elasticity gap, {nm}",
                 f"{v['spent'][0] - v['renewing'][0]:+.2f} at the {nm}")

# ------------------------------------------------- designing to a specification
Fe = load("feasibility.json")
if Fe:
    reach, big = Fe.get("reach") or {}, max(Fe.get("scales") or [0])
    r = reach.get(str(big))
    if r:
        need("largest volume, best density",
             f"reaches is {100 * r['best_fill']['fill']:.2f} % of close packing")
        need("largest volume, fewest segments",
             f"any reaches is {r['fewest_vessels']['vessels']:.0f}")
        need("largest volume, lowest variation",
             f"lowest variation any reaches is {r['lowest_cv']['cv']:.3f}")
    for S, b in sorted((Fe.get("infeasible") or {}).items()):
        need(f"slack of the binding requirement at scale {S}",
             f"a slack of {b['best'][b['binding']]:+.2f}")
    for S, c in sorted((Fe.get("chosen") or {}).items()):
        if "margin" in c:
            need(f"margin of the chosen configuration at scale {S}",
                 f"a margin of {c['margin']:+.2f} on the search seeds")
    for S, h in sorted((Fe.get("held_out") or {}).items()):
        if "margin" in h:
            need(f"held-out margin at scale {S}",
                 f"{h['margin']:+.2f} held out")
    if Fe.get("optimism") is not None:
        need("optimism of the search block",
             f"by {abs(Fe['optimism']):.2f} on average")


def main():
    if not DOC.exists():
        raise SystemExit(f"no manuscript at {DOC}")
    # The manuscript sets a minus as U+2212; compare against a plain hyphen.
    # It is also hard-wrapped, so a quoted phrase can fall across two lines
    # and a literal search would miss it. Runs of whitespace collapse to one
    # space on both sides, which only ever makes a match easier to find.
    text = " ".join(DOC.read_text(encoding="utf-8").replace("\u2212", "-").split())
    if not checks:
        print("no results to check against; run `make paper` first")
        return 0
    checks[:] = [(lb, " ".join(w.split())) for lb, w in checks]
    bad = [(label, want) for label, want in checks if want not in text]
    for label, want in checks:
        print(f"  {'ok  ' if want in text else 'FAIL'} {label}: {want}")
    print()
    if bad:
        print(f"{len(bad)} of {len(checks)} numbers in MANUSCRIPT.md no longer "
              f"match the results. The results are right and the prose is "
              f"stale: edit the sentence to the value printed above.")
        return 1
    print(f"all {len(checks)} model numbers in MANUSCRIPT.md match the results")
    return 0


if __name__ == "__main__":
    sys.exit(main())
